<?php
/**
 * DEVELOPMENT ONLY. Builds public_html/assets/icons/lucide.svg — an SVG
 * <symbol> sprite containing exactly the Lucide icons the PHP templates and
 * JS use (icon('name'), 'icon' => 'name', data-icon="name", svgIcon('name')).
 * Icon geometry is read from the Next.js project's lucide-react package
 * (ISC licence) so the icons are identical to the original UI.
 *
 * Usage: php hrms-php/dev/build_icons.php <path-to-lucide-react/dist/esm/icons>
 */
declare(strict_types=1);

$iconsDir = rtrim($argv[1] ?? '', '/\\');
if (!is_dir($iconsDir)) {
    fwrite(STDERR, "Usage: php build_icons.php <lucide-react/dist/esm/icons>\n");
    exit(2);
}
$root = dirname(__DIR__);
$names = [];
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/app'));
$files = array_merge(iterator_to_array($it), glob($root . '/public_html/assets/js/*.js') ?: []);
foreach ($files as $file) {
    $file = (string)$file;
    if (!preg_match('/\.(php|js)$/', $file) || str_contains($file, DIRECTORY_SEPARATOR . 'vendor' . DIRECTORY_SEPARATOR)) {
        continue;
    }
    $src = file_get_contents($file);
    // Icon names are passed around as plain string literals (icon('x'),
    // stat_card(..., 'users'), empty_state('inbox', ...), svgIcon('x')), so
    // take every quoted kebab-case literal that is an actual Lucide icon.
    preg_match_all("/['\"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['\"]/", $src, $m);
    foreach ($m[1] as $n) {
        if (resolve_icon_file($iconsDir, $n) !== null) {
            $names[$n] = true;
        }
    }
}
ksort($names);

$out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
        '<!-- Lucide icons (ISC licence) — generated by dev/build_icons.php -->'];
$missing = [];
foreach (array_keys($names) as $name) {
    $file = resolve_icon_file($iconsDir, $name);
    if ($file === null) {
        $missing[] = $name;
        continue;
    }
    $js = file_get_contents($file);
    if (!preg_match('/node:\s*\[(.*)\]\s*\};/s', $js, $nm)) {
        $missing[] = $name;
        continue;
    }
    preg_match_all('/\[\s*"(\w+)",\s*\{(.*?)\}\s*\]/s', $nm[1], $els, PREG_SET_ORDER);
    $inner = '';
    foreach ($els as $el) {
        preg_match_all('/([\w-]+):\s*"([^"]*)"/', $el[2], $attrs, PREG_SET_ORDER);
        $a = '';
        foreach ($attrs as $attr) {
            if ($attr[1] === 'key') {
                continue;
            }
            $a .= ' ' . $attr[1] . '="' . htmlspecialchars($attr[2], ENT_QUOTES) . '"';
        }
        $inner .= '<' . $el[1] . $a . '/>';
    }
    $out[] = '<symbol id="' . $name . '" viewBox="0 0 24 24">' . $inner . '</symbol>';
}
$out[] = '</svg>';
file_put_contents($root . '/public_html/assets/icons/lucide.svg', implode("\n", $out) . "\n");
echo count($names) - count($missing) . " icons written";
if ($missing) {
    echo "; MISSING: " . implode(', ', $missing);
    echo PHP_EOL;
    exit(1);
}
echo PHP_EOL;

/**
 * Finds the .mjs file holding an icon's geometry: follows alias files
 * ("export { default } from './chart-column.mjs'"), and for React component
 * names without a file of their own (Fingerprint → fingerprint-pattern)
 * looks the PascalCase name up in the package index.
 */
function resolve_icon_file(string $iconsDir, string $name, int $depth = 0): ?string
{
    if ($depth > 3) {
        return null;
    }
    $file = "$iconsDir/$name.mjs";
    if (!is_file($file)) {
        $pascal = str_replace(' ', '', ucwords(str_replace('-', ' ', $name)));
        $index = @file_get_contents(dirname($iconsDir) . '/lucide-react.mjs') ?: '';
        if (preg_match('/export \{[^}]*\bdefault as ' . preg_quote($pascal, '/') . '\b[^}]*\} from \'\.\/icons\/([a-z0-9-]+)\.mjs\'/', $index, $m)) {
            return resolve_icon_file($iconsDir, $m[1], $depth + 1);
        }
        return null;
    }
    $js = file_get_contents($file);
    if (!str_contains($js, '__iconData') && preg_match("/from '\.\/([a-z0-9-]+)\.mjs'/", $js, $m)) {
        return resolve_icon_file($iconsDir, $m[1], $depth + 1);
    }
    return $file;
}
